package main

import (
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/tls"
	"crypto/x509"
	"crypto/x509/pkix"
	"encoding/pem"
	"fmt"
	"log"
	"math/big"
	"net"
	"path/filepath"
	"time"
)

// certDir is where the node keeps the self-signed AnyTLS certificate it
// generates; main sets it to the config file's directory. Empty keeps the
// certificate in memory only.
var certDir string

// anytlsCert returns the certificate for an AnyTLS inbound: cert_pem/key_pem
// when given, else the cert/key files, which must exist. With neither, the
// node uses a self-signed ECDSA certificate for serverName, kept in certDir
// and regenerated when serverName changes (AnyTLS clients normally skip
// verification, so this is enough unless the user brings a real one).
func anytlsCert(c InboundConfig) (tls.Certificate, error) {
	switch {
	case c.CertPEM != "" || c.KeyPEM != "":
		return tls.X509KeyPair([]byte(c.CertPEM), []byte(c.KeyPEM))
	case c.Cert != "" || c.Key != "":
		cert, err := tls.LoadX509KeyPair(c.Cert, c.Key)
		if err != nil {
			return cert, fmt.Errorf("anytls certificate: %w", err)
		}
		return cert, nil
	}
	if certDir == "" {
		return selfSignedPair(c.ServerName)
	}
	return loadOrCreateCert(filepath.Join(certDir, "anytls.crt"), filepath.Join(certDir, "anytls.key"), c.ServerName)
}

// selfSignedOrg marks certificates generated by keel-node.
const selfSignedOrg = "keel-node self-signed"

// loadOrCreateCert loads the self-signed pair at certPath/keyPath, or
// generates a new one when it is missing, unreadable or for another name.
func loadOrCreateCert(certPath, keyPath, serverName string) (tls.Certificate, error) {
	if cert, err := tls.LoadX509KeyPair(certPath, keyPath); err == nil && matchesName(cert, serverName) {
		return cert, nil
	}
	certPEM, keyPEM, err := selfSigned(serverName)
	if err != nil {
		return tls.Certificate{}, err
	}
	if err = writeFileAtomic(keyPath, keyPEM, 0o600); err != nil {
		return tls.Certificate{}, err
	}
	if err = writeFileAtomic(certPath, certPEM, 0o644); err != nil {
		return tls.Certificate{}, err
	}
	log.Printf("generated self-signed certificate %s for %s", certPath, certName(serverName))
	return tls.X509KeyPair(certPEM, keyPEM)
}

func selfSignedPair(serverName string) (tls.Certificate, error) {
	certPEM, keyPEM, err := selfSigned(serverName)
	if err != nil {
		return tls.Certificate{}, err
	}
	return tls.X509KeyPair(certPEM, keyPEM)
}

func certName(serverName string) string {
	if serverName == "" {
		return "localhost"
	}
	return serverName
}

func matchesName(cert tls.Certificate, serverName string) bool {
	leaf, err := x509.ParseCertificate(cert.Certificate[0])
	return err == nil && leaf.VerifyHostname(certName(serverName)) == nil
}

func selfSigned(serverName string) (certPEM, keyPEM []byte, err error) {
	serverName = certName(serverName)
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return nil, nil, err
	}
	serial, err := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 127))
	if err != nil {
		return nil, nil, err
	}
	now := time.Now()
	template := &x509.Certificate{
		SerialNumber: serial,
		Subject:      pkix.Name{CommonName: serverName, Organization: []string{selfSignedOrg}},
		NotBefore:    now.Add(-time.Hour),
		NotAfter:     now.AddDate(10, 0, 0),
		KeyUsage:     x509.KeyUsageDigitalSignature,
		ExtKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
	}
	if ip := net.ParseIP(serverName); ip != nil {
		template.IPAddresses = []net.IP{ip}
	} else {
		template.DNSNames = []string{serverName}
	}
	der, err := x509.CreateCertificate(rand.Reader, template, template, &key.PublicKey, key)
	if err != nil {
		return nil, nil, err
	}
	keyDER, err := x509.MarshalPKCS8PrivateKey(key)
	if err != nil {
		return nil, nil, err
	}
	return pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}),
		pem.EncodeToMemory(&pem.Block{Type: "PRIVATE KEY", Bytes: keyDER}), nil
}
